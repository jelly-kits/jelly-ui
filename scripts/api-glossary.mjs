/** 事件名里的 v-model 更新：update:foo → foo 更新时触发 */
const updateEvent = (name) => {
  const target = name.slice('update:'.length)
  if (!target) return undefined
  return `v-model 的 ${target} 更新时触发`
}

const pick = (map, name) => {
  if (Object.prototype.hasOwnProperty.call(map, name)) return map[name]
  if (name.startsWith('update:')) return updateEvent(name)
  return undefined
}

export const describeAttribute = (name) => pick(attributeGlossary, name)
export const describeEvent = (name) => pick(eventGlossary, name)
export const describeSlot = (name) => pick(slotGlossary, name)
export const describeExpose = (name) => pick(exposeGlossary, name)

export const glossaries = { attributeGlossary, eventGlossary, slotGlossary, exposeGlossary }
